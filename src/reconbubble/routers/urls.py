def build(st: AppState, app) -> APIRouter:
    router = APIRouter()

    @router.get("/urls")
    def urls_redirect(request: Request):
        from fastapi import Response as FResponse
        show_out = request.query_params.get("show_out", "0")
        target = f"/subdomains?show_out={show_out}"
        return FResponse(status_code=302, headers={"Location": target})

    @router.get("/urls/export")
    def export_urls():
        with st.db() as s:
            rows = s.execute(select(WebUrl).order_by(WebUrl.url.asc())).scalars().all()
        domain_urls = []
        ip_urls = []
        ip_re = re.compile(r"^\d{1,3}(\.\d{1,3}){3}$")
        for x in rows:
            try:
                h = (urlsplit(x.url).hostname or "").strip().lower()
                if not h:
                    h = (urlsplit("http://" + x.url).hostname or "").strip().lower()
            except Exception:
                h = ""
            if h and ip_re.match(h):
                ip_urls.append(x.url)
            else:
                domain_urls.append(x.url)
        lines = sorted(domain_urls) + [""] + sorted(ip_urls)
        txt = "\n".join(lines)
        return Response(
            content=txt,
            media_type="text/plain",
            headers={
                "Content-Disposition": "attachment; filename=reconbubble-urls.txt"
            },
        )

    # RDAP/whois lookup
    return router
